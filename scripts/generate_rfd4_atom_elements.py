"""Regenerate the element lookup tables in `tools/rfd4/numbering.py`.

Source: the RCSB Chemical Component Dictionary, one component per file at
``https://files.rcsb.org/ligands/view/<ID>.cif``, read 2026-11-03. The columns
used are ``_chem_comp_atom.atom_id`` and ``_chem_comp_atom.type_symbol``.

Why generated rather than written by hand: three rounds of review found a
defect in `_element_of` each time it reasoned from the SHAPE of an atom name,
and two consecutive repairs were wrong in opposite directions. A name's shape
cannot settle it -- in a file that left-justifies atom names and omits columns
77-78, a leucine's ``CD1`` and cadmium's ``CD1`` are byte-identical. The only
way out is to stop guessing and look the pair up, and the only honest way to
hold a lookup table is to generate it from the dictionary that defines it.

Three constants are emitted, between the markers in `tools/rfd4/numbering.py`:

* ``_CCD_COVERED_RESIDUES`` -- the 20 standard amino acids, ``UNK``, water and
  every name in ``_MODRES_EQUIV``. Inside one of these the element is NEVER
  guessed from the name's shape. This is the element tables' domain and NOT the
  set of residues the module treats as polymer: `_is_polymer` applies no
  residue-name test, so it admits names that are not here.
* ``_CCD_ELEMENT_EXCEPTIONS`` -- for those residues, only the atoms whose
  element is not the first alphabetic character of the atom name. There is no
  assertion to make here: this script reads every atom of those residues and
  lists exactly the ones that differ, so an atom it leaves out is one the
  dictionary says first-letter gets right. It prints the TOTAL it read and the
  number it listed; the difference is how many the rule covers.
* ``_MONATOMIC_ION_ELEMENTS`` -- for each candidate element symbol, the CCD
  component of that name when it is monatomic, and its element. The candidate
  list below is hand-written; what each one's element IS, and whether a
  component of that name exists and is monatomic at all, comes from the CCD.

Run it with the repo venv and no arguments. It rewrites the marked block in
place; `git diff` is then the evidence that the committed table matches the
dictionary.
"""

from __future__ import annotations

import shlex
import sys
import urllib.error
import urllib.request
from pathlib import Path

NUMBERING = Path(__file__).resolve().parent.parent / "tools" / "rfd4" / "numbering.py"
BEGIN = "# --- BEGIN GENERATED by scripts/generate_rfd4_atom_elements.py ---"
END = "# --- END GENERATED ---"
URL = "https://files.rcsb.org/ligands/view/{}.cif"

STANDARD_AA = [
    "ALA", "ARG", "ASN", "ASP", "CYS", "GLN", "GLU", "GLY", "HIS", "ILE",
    "LEU", "LYS", "MET", "PHE", "PRO", "SER", "THR", "TRP", "TYR", "VAL",
    "UNK",
]
# Water: `HOH` and `DOD` are CCD components, `WAT` and `H2O` are not. The two
# that are not stay out of the generated table and fall through to the first
# alphabetic character, which is right for `O`, `H1` and `H2`.
WATER = ["HOH", "DOD"]
# Mirrors `_MODRES_EQUIV` in numbering.py. Only ONE direction of that is
# checked: `test_every_polymer_residue_name_has_a_ccd_element_table` fails if
# `_MODRES_EQUIV` grows a name this list does not cover. A name added HERE and
# not there fails nothing; the two sets are equal as committed.
MODRES = [
    "MSE", "CME", "CSO", "SEP", "TPO", "PTR", "KCX", "HYP", "LLP",
    "CSD", "OCS", "MLY", "M3L", "CAS", "CSS", "CSX", "PCA", "SAC",
]
# Candidate monatomic ion names, hand-written. Everything about each one -- its
# element, and whether a CCD component of that name exists and holds a single
# atom -- is read from the dictionary, and a candidate that fails either test
# is dropped with a line on stderr.
ION_CANDIDATES = [
    "AG", "AL", "AS", "AU", "BA", "BE", "BI", "BR", "CA", "CD", "CE", "CL",
    "CO", "CR", "CS", "CU", "DY", "ER", "EU", "FE", "GA", "GD", "GE", "HF",
    "HG", "HO", "IN", "IR", "LA", "LI", "LU", "MG", "MN", "MO", "NA", "NB",
    "ND", "NI", "OS", "PB", "PD", "PR", "PT", "RB", "RE", "RH", "RU", "SB",
    "SC", "SE", "SI", "SM", "SN", "SR", "TA", "TB", "TC", "TE", "TH", "TI",
    "TL", "TM", "YB", "ZN", "ZR",
    "B", "C", "F", "H", "I", "K", "N", "O", "P", "S", "U", "V", "W", "Y",
]


def fetch_atoms(comp_id: str) -> list[tuple[str, str]] | None:
    """``(atom_id, type_symbol)`` for one component, or None if there is none.

    Reads the ``_chem_comp_atom`` loop by its declared column order. An earlier
    draft matched any line beginning with the component id instead, which also
    caught the single-row ``_chem_comp`` descriptor block and reported ``ZN`` as
    a four-atom component.

    ``None`` means the dictionary has no such component, and ONLY that: a 404.
    Every other outcome raises, including a 200 whose body parses to no atoms
    at all.

    Two earlier revisions were looser in the same direction, and the ion loop
    is why it matters: it SKIPS a ``None``, so anything that reads as absence
    writes a smaller ion table and pushes those residues back onto the shape
    fallback this script exists to retire, with the run still reporting
    success. The first revision returned ``None`` for every exception, so a
    timeout or a 5xx read as absence. The second fixed that but kept an
    ``or None`` tail, so a 200 this parser could not read -- a dictionary
    format change, a truncated body, an error page served as 200 -- read as
    absence too, which is the failure the paragraph above claimed was gone
    (``test_a_200_that_parses_to_no_atoms_raises``).
    """
    try:
        with urllib.request.urlopen(URL.format(comp_id), timeout=60) as fh:
            text = fh.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as exc:
        if exc.code != 404:
            raise
        print(f"  {comp_id}: not in the dictionary (404)", file=sys.stderr)
        return None
    atoms = _parse_loop(text) or _parse_single(text)
    if not atoms:
        raise RuntimeError(
            f"{comp_id}: served {len(text)} bytes that parse to no atoms; "
            "the CCD format or the response has changed"
        )
    return atoms


def _split(s: str) -> list[str]:
    try:
        return shlex.split(s)
    except ValueError:
        return s.split()


def _parse_loop(text: str) -> list[tuple[str, str]]:
    """The multi-atom form: a ``loop_`` with ``_chem_comp_atom.*`` headers."""
    out: list[tuple[str, str]] = []
    headers: list[str] = []
    for line in text.splitlines():
        s = line.strip()
        if s == "loop_":
            headers = []
            continue
        if s.startswith("_chem_comp_atom."):
            headers.append(s.split()[0])
            continue
        if s.startswith("_"):
            if out:
                break
            headers = []
            continue
        if not s or s.startswith("#"):
            if out:
                break
            continue
        if len(headers) < 4:
            continue
        tok = _split(s)
        if len(tok) != len(headers):
            continue
        row = dict(zip(headers, tok))
        symbol = row["_chem_comp_atom.type_symbol"]
        if symbol.isalpha():
            out.append((row["_chem_comp_atom.atom_id"].upper(),
                        symbol.capitalize()))
    return out


def _parse_single(text: str) -> list[tuple[str, str]]:
    """The one-atom form: ``_chem_comp_atom.<key> <value>`` pairs, no loop.

    A monatomic component such as ``ZN`` is written this way, and a loop-only
    reader reports it as having no atoms at all.
    """
    row: dict[str, str] = {}
    for line in text.splitlines():
        s = line.strip()
        if not s.startswith("_chem_comp_atom."):
            continue
        tok = _split(s)
        if len(tok) == 2:
            row[tok[0]] = tok[1]
    atom_id = row.get("_chem_comp_atom.atom_id", "")
    symbol = row.get("_chem_comp_atom.type_symbol", "")
    if not atom_id or not symbol.isalpha():
        return []
    return [(atom_id.upper(), symbol.capitalize())]


def main() -> int:
    covered: list[str] = []
    exceptions: dict[str, dict[str, str]] = {}
    checked = 0
    for comp_id in STANDARD_AA + WATER + MODRES:
        atoms = fetch_atoms(comp_id)
        if atoms is None:
            print(f"ABORT: no CCD atoms for {comp_id}", file=sys.stderr)
            return 1
        covered.append(comp_id)
        for atom_id, symbol in atoms:
            checked += 1
            first = next((c for c in atom_id if c.isalpha()), "")
            if symbol.upper() != first.upper():
                exceptions.setdefault(comp_id, {})[atom_id] = symbol
    print(f"{len(covered)} residues, {checked} atoms checked, "
          f"{sum(len(v) for v in exceptions.values())} element exceptions")

    ions: dict[str, str] = {}
    for comp_id in ION_CANDIDATES:
        atoms = fetch_atoms(comp_id)
        if atoms is None:
            continue
        if len(atoms) != 1:
            print(f"  {comp_id}: {len(atoms)} atoms, not monatomic, dropped",
                  file=sys.stderr)
            continue
        if atoms[0][1] == "H":
            print(f"  {comp_id}: monatomic hydrogen, dropped", file=sys.stderr)
            continue
        ions[comp_id] = atoms[0][1]
    dropped = [c for c in ION_CANDIDATES if c not in ions]
    print(f"{len(ions)} monatomic ion components of "
          f"{len(ION_CANDIDATES)} candidates; dropped: {' '.join(dropped)}")

    def wrap(prefix: str, items: list[str], width: int = 76) -> list[str]:
        lines, cur = [], prefix
        for it in items:
            if len(cur) + len(it) + 1 > width and cur != prefix:
                lines.append(cur)
                cur = "    " + it
            else:
                cur = (cur + " " + it) if cur != prefix else prefix + it
        lines.append(cur)
        return lines

    body = [
        BEGIN,
        f"# {len(covered)} residues, {checked} atoms read from the CCD. Each atom NOT",
        "# listed in `_CCD_ELEMENT_EXCEPTIONS` below was checked by the generator: its",
        "# `type_symbol` equals the first alphabetic character of its `atom_id`, so for",
        "# these residues that character is the element, measured and not assumed.",
        "_CCD_COVERED_RESIDUES = frozenset({",
        *wrap("    ", [f'"{c}",' for c in covered]),
        "})",
        "",
        "# The atoms of those residues whose element is NOT the name's first letter.",
        "_CCD_ELEMENT_EXCEPTIONS: dict[str, dict[str, str]] = {",
    ]
    for comp_id in sorted(exceptions):
        pairs = ", ".join(f'"{a}": "{s}"'
                          for a, s in sorted(exceptions[comp_id].items()))
        body.append(f'    "{comp_id}": {{{pairs}}},')
    body += [
        "}",
        "",
        f"# The {len(ions)} of {len(ION_CANDIDATES)} candidate element symbols that name a",
        "# single-atom CCD component, and the element that component holds. Inside one",
        "# of these residues every atom is that element, whatever the atom is named.",
        "# Candidates dropped because the CCD has no such component, or because its",
        "# component holds more than one atom, or holds one hydrogen:",
        *[f"# {ln.strip()}" for ln in wrap("", dropped or ["(none)"], 72)],
        "_MONATOMIC_ION_ELEMENTS: dict[str, str] = {",
    ]
    items = [f'"{c}": "{ions[c]}",' for c in sorted(ions)]
    body += wrap("    ", items)
    body += ["}", END]

    raw = NUMBERING.read_bytes()
    assert raw.count(b"\r\n") == raw.count(b"\n"), "numbering.py is not CRLF"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    head, _, rest = text.partition(BEGIN)
    assert rest, "BEGIN marker not found"
    _, _, tail = rest.partition(END)
    assert tail, "END marker not found"
    new = head + "\n".join(body) + tail
    NUMBERING.write_bytes(new.replace("\n", "\r\n").encode("utf-8"))
    print(f"rewrote {NUMBERING}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
