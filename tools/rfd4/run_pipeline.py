def new_design_stream() -> dict[str, Any]:
    """Sweep state: files already taken, entries delivered, next rank, last beat."""
    return {"taken": set(), "designs": [], "next_rank": 0, "beat_at": time.monotonic()}


def target_chain_sequence(cif_text: str, chain: str) -> str:
    """The target chain's one-letter sequence, or ``""`` when it has none.

    Takes the CIF TEXT, not ``load_target``'s ``atoms``: those are
    ``atom_names_by_residue``'s ``(chain, residue) -> atom names`` pairs, a
    shape ``chain_sequences`` cannot read. Pinned together with
    ``load_target`` by
    tests/test_rfd4_pipeline.py::test_the_target_chain_sequence_comes_off_a_loaded_target.

    ``chain`` is an author chain id, which is what ``resolve_target_chain``
    returns and what ``chain_sequences`` keys on.
    """
    try:
        return chain_sequences(read_atom_site(cif_text)).get(chain, "")
    except ValueError as exc:
        logger.warning("target: sequence read failed (%s)", exc)
        return ""


def _designed_sequence(cif_text: str, target_sequence: str) -> str:
    """The binder chain's one-letter sequence, or ``""`` when it is not certain.

    The designed chain is picked by SEQUENCE IDENTITY against the known
    target, not by chain id and not by length: rung 4's ``pdl1_binder_4`` is
    116 aa against a 115 aa target, so a length rule mis-picks it
    (docs/scoping/rung5-probe/prep_rung5.py module docstring). One occurrence
    of the target sequence is removed rather than every chain matching it, so
    a design that copies the target verbatim -- the shape recorded for
    proteina in memory note ``proteina-target-self-copy`` -- still yields its
    sequence.

    ``resolve_target_chain`` refuses a multi-chain target (pinned by
    tests/test_rfd4_pipeline.py::test_a_two_chain_target_is_refused), so a
    design file holds the one target chain plus the binder and exactly one
    chain is left after the removal. Anything else
    returns ``""``: no key at all is better than a wrong sequence, because
    the sequence is what the chained Boltz-2 fold folds
    (shared/refold.py::_candidate_sequence).
    """
    if not target_sequence:
        return ""
    try:
        seqs = chain_sequences(read_atom_site(cif_text))
    except ValueError as exc:
        logger.warning("design: sequence read failed (%s) - no sequence carried", exc)
        return ""
    remaining = list(seqs.values())
    if target_sequence in remaining:
        remaining.remove(target_sequence)
    if len(remaining) != 1:
        logger.warning(
            "design: %d candidate binder chains after dropping the target "
            "- no sequence carried", len(remaining),
        )
        return ""
    if "X" in remaining[0]:
        logger.warning(
            "design: binder chain holds a non-standard residue - no sequence carried"
        )
        return ""
    return remaining[0]


def _upload_design(
    cif_path: Path, rank: int, *, upload_endpoint: str, job_token: str,
    target_sequence: str = "",
) -> dict | None:
    """Upload one finished design and build its manifest entry, or None on failure.

    The key is rank-prefixed so per-sample outputs cannot collide in storage,
    and it keeps the ``.cif`` extension because the download label follows the
    storage key rather than the MIME type (memory note
    ``download-label-follows-key-not-mime``). ``shared/storage.py`` takes the
    content type as a plain parameter with no allow-list at the signing side
    (shared/storage.py:66, :97).

    NO SCORE. Every numeric column upstream produces lands in the two metrics
    CSVs, and scope §5.8's timings show both arriving in the same poll interval
    as the LAST design, so at stream time there is nothing numeric to carry.
    The score arrives from a chained Boltz-2 fold instead, which needs the
    designed chain's sequence -- hence the fourth key.

    ``rank``, ``name`` and ``pdb_key`` are in ``_sanitize_candidate``'s
    allow-list; ``sequence`` is NOT, deliberately. That allowlist runs on one
    path only, the mid-run heartbeat (webhooks/modal.py:353), and a terminal
    COMPLETED payload reaches ``complete_job`` unfiltered
    (webhooks/modal.py:144-151, :173-180), which is where the refold reads it
    from -- ``job_refold`` refuses a source job that is not ``succeeded``
    (blueprints/jobs.py::job_refold). So the sequence survives where it is
    used and is absent from the live/partial snapshot, which is the same
    behaviour every other refold source tool already has.
    """
    text = cif_path.read_text()
    uniq = f"{rank:03d}_{cif_path.stem}"
    cif_key = f"{uniq}.cif"
    try:
        urls = request_upload_urls(upload_endpoint, job_token, [cif_key])
        upload_file(urls[cif_key], text.encode("utf-8"), "chemical/x-mmcif")
    except Exception as exc:
        logger.warning("design %s: upload failed (%s) — skipping", cif_key, exc)
        return None
    entry = {"rank": rank, "name": uniq, "pdb_key": cif_key}
    seq = _designed_sequence(text, target_sequence)
    if seq:
        entry["sequence"] = seq
    return entry


def sweep_designs(
    out_dir: Path,
    stream: dict[str, Any],
    upload_one: Callable[[Path, int], dict | None],
    *,
    mid_run: bool,
    webhook_url: str = "",
    job_id: str = "",
    planned_total: int = 0,
) -> None:
    """Upload and stream every design not taken by an earlier sweep.

    Called on a timer while ``rfd4-generate`` runs, then once more after it
    exits. Scope §5.8's rung-4 artefact timed two designs landing inside one
    5 s poll interval, so a sweep taking several files at once is the normal
    case, and ranks are completion order only to within a poll interval --
    within one sweep they follow the sorted path. They are not quality ranks.

    The final sweep carries the MEASURED total rather than the plan, for the
    same reason iggm's does (tools/iggm/run_pipeline.py:693, comment at :670-678): a run that
    produced fewer designs than planned would otherwise leave the snapshot
    short, and ``shared/job_recovery.py::_completion_signal`` reads that
    snapshot to decide whether a killed container's designs are delivered.
    """
    paths = collect_design_cifs(out_dir)
    designs_total = planned_total if mid_run else len(paths)
    for path in paths:
        key = str(path)
        if key in stream["taken"]:
            continue
        try:
            if path.stat().st_size == 0:
                continue
        except OSError:
            continue
        rank = stream["next_rank"]
        try:
            entry = upload_one(path, rank)
        except Exception as exc:
            # Mid-run this is a retry: no upload was attempted, so no key is
            # spent and a later sweep reoffers the rank. The final sweep has no
            # later sweep, so the design is dropped and the run still completes
            # -- recorded rather than silent, because that sweep's
            # designs_total counts this file, so the closing snapshot reads
            # completed < total.
            logger.warning("design %s: not readable this sweep (%s)", path.name, exc)
            continue
        stream["taken"].add(key)
        stream["next_rank"] = rank + 1
        if entry is None:
            continue
        stream["designs"].append(entry)
        send_heartbeat(
            webhook_url, job_id, stage="designing",
            designs_completed=len(stream["designs"]),
            designs_total=designs_total,
            new_candidate=entry,
        )
        stream["beat_at"] = time.monotonic()
    if mid_run and time.monotonic() - stream["beat_at"] >= KEEPALIVE_INTERVAL_S:
        # The hub refreshes gpu_seconds_used, which is what a cancel bills, only
        # when a beat arrives (webhooks/modal.py::_handle_heartbeat), and scope
        # §5.8 measured 128.2 s before the first design appeared.
        send_heartbeat(
            webhook_url, job_id, stage="designing",
            designs_completed=len(stream["designs"]),
            designs_total=designs_total,
        )
        stream["beat_at"] = time.monotonic()
    if not mid_run:
        # Unconditional: the loop above beats only on a design it TOOK, so a
        # final sweep that took nothing would leave a mid-run beat carrying the
        # PLAN as the snapshot's last word. No ``new_candidate``, so this cannot
        # re-deliver a design.
        send_heartbeat(
            webhook_url, job_id, stage="designing",
            designs_completed=len(stream["designs"]),
            designs_total=designs_total,
        )


def rfd4_command(spec_path: Path, out_dir: Path, num_designs: int) -> list[str]:
    """The full ``rfd4-generate`` argv for this run.

    Built from ``RFD4_OVERRIDES`` and ``RFD4_METRICS_TAGS`` so the guard test
    can assert on the constants rather than on a reconstruction (scope §5.3
    line 364).
    """
    return [
        "rfd4-generate",
        *RFD4_OVERRIDES,
        f"inputs={spec_path}",
        f"num_replicates={num_designs}",
        "metrics_tags=[" + ",".join(RFD4_METRICS_TAGS) + "]",
        f"out_dir={out_dir}",
    ]


def run_rfd4(
    spec_path: Path,
    out_dir: Path,
    num_designs: int,
    on_poll: Callable[[], None] | None = None,
    poll_seconds: float = 5.0,
) -> int:
    """Run one ``rfd4-generate``. stdout/stderr live-stream to Modal logs.

    ``on_poll`` runs on this thread between waits, so no two sweeps overlap and
    a slow callback only delays the next poll. A callback that raises is logged
    and the run continues.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = rfd4_command(spec_path, out_dir, num_designs)
    logger.info("rfd4 cmd: %s", " ".join(cmd))
    proc = subprocess.Popen(cmd, stdout=sys.stdout, stderr=sys.stderr)
    while True:
        try:
            return proc.wait(timeout=poll_seconds)
        except subprocess.TimeoutExpired:
            pass
        if on_poll is not None:
            try:
                on_poll()
            except Exception as exc:
                logger.warning("design sweep raised (%s); the run continues", exc)


# ===========================================================================
# Main
# ===========================================================================


def main() -> None:
    start = time.time()
    payload = parse_payload()
    job_spec = payload.get("job_spec") or {}

    preset = str(job_spec.get("preset") or os.environ.get("JOB_TIER") or "binder_design")
    webhook_url = str(payload.get("webhook_url") or os.environ.get("WEBHOOK_URL") or "")
    job_id = str(payload.get("job_id") or os.environ.get("JOB_ID") or "")
    job_token = str(payload.get("job_token") or os.environ.get("JOB_TOKEN") or "")
    upload_endpoint = str(payload.get("upload_urls_endpoint") or "")
    input_url = str(payload.get("input_presigned_url") or "")
    if not upload_endpoint:
        _fail("preflight", "env", "upload_urls_endpoint missing from the payload")

    binder_length = parse_binder_length(job_spec.get("binder_length"))
    num_designs = parse_num_designs(job_spec.get("nsamples"))

    send_heartbeat(webhook_url, job_id, stage="preparing", designs_total=num_designs)

    designs_out: list[dict] = []
    runtime_seconds = 0
    with tempfile.TemporaryDirectory(prefix="rfd4_") as tmp:
        workdir = Path(tmp)
        try:
            out_dir = workdir / "out"
            target_path = download_target(input_url, workdir / "target_upload")
            cif_path, mapping, atoms = load_target(target_path, workdir)
            chain = resolve_target_chain(mapping, str(job_spec.get("target_chain") or ""))
            n_res = validate_sizes(mapping, chain, binder_length)
            contig = build_contig(mapping, chain, binder_length)
            asym = mapping.polymer_entries(chain)[0].label_asym_id
            selections = build_hotspot_selections(
                mapping, atoms, hotspot_tokens(job_spec), chain
            )
            try:
                spec_path = write_condition_spec(
                    workdir / "condition_spec.yaml",
                    cif_path=cif_path,
                    contig=contig,
                    asym=asym,
                    hotspot_selections=selections,
                )
            except ValueError as exc:
                _fail("input", "spec", str(exc))
                raise
            logger.info(
                "target chain %s (%d aa, asym %s), contig %r, %d hotspot selections",
                chain, n_res, asym, contig, len(selections),
            )

            stream = new_design_stream()

            # Read once, so each design file only has to be told which
            # sequence is NOT the binder. NOT from ``atoms``: that is
            # ``atom_names_by_residue``'s residue -> atom-name map
            # (``load_target``'s third return), whose keys are tuples, so
            # ``chain_sequences`` would index a tuple with a string.
            target_seq = target_chain_sequence(
                cif_path.read_text(errors="replace"), chain
            )
            if not target_seq:
                logger.warning(
                    "target chain %s yielded no CA sequence; designs will carry "
                    "no sequence and cannot be folded downstream", chain,
                )

            def upload_one(path: Path, rank: int) -> dict | None:
                return _upload_design(
                    path, rank, upload_endpoint=upload_endpoint, job_token=job_token,
                    target_sequence=target_seq,
                )

            def _sweep(mid_run: bool) -> None:
                sweep_designs(
                    out_dir, stream, upload_one,
                    mid_run=mid_run,
                    webhook_url=webhook_url, job_id=job_id,
                    planned_total=num_designs,
                )

            rc = run_rfd4(spec_path, out_dir, num_designs, on_poll=lambda: _sweep(True))
            if rc != 0:
                # Designs the sweeps already uploaded stay in Storage and stay
                # listed, while bucket "run" is unmapped in
                # shared/jobs.py::_ERROR_BUCKET_TO_FAILURE_CLASS and so refunds
                # in full -- the delivered-and-refunded shape recorded for iggm
                # (tools/iggm/run_pipeline.py:903-928) and open with Leo there.
                # Not re-decided here.
                _fail("run", "rfd4-generate", f"rfd4-generate exited with code {rc}")

            design_cifs = collect_design_cifs(out_dir)
            if not design_cifs:
                _fail(
                    "run", "output", "rfd4-generate produced no design CIFs",
                    runtime_seconds=int(time.time() - start),
                )

            # rfd4-generate has exited, so nothing is still being written: take
            # whatever the timed sweeps did not, and beat the measured total.
            _sweep(False)
            designs_out = stream["designs"]

            # Before the artifact uploads, so a run that delivers no design
            # uploads no artifacts to Storage for a failed job.
            if not designs_out:
                _fail(
                    "storage", "no_designs",
                    f"all {len(design_cifs)} designs failed to upload — nothing to deliver.",
                    runtime_seconds=int(time.time() - start),
                )

            artifact_keys: list[str] = []
            for art in collect_artifacts(out_dir):
                key = f"artifacts/{art.name}"
                ctype = {".csv": "text/csv", ".png": "image/png"}.get(
                    art.suffix.lower(), "application/octet-stream"
                )
                try:
                    urls = request_upload_urls(upload_endpoint, job_token, [key])
                    upload_file(urls[key], art.read_bytes(), ctype)
                    artifact_keys.append(key)
                except Exception as exc:
                    logger.warning("artifact %s: upload failed (%s)", key, exc)

            # Deliver the COMPLETED result BEFORE the raw-capture tar runs, for
            # the reason tools/iggm/run_pipeline.py:958-962 gives: a run
            # finishing near the subprocess timeout can be SIGKILLed mid-tar,
            # and a result written only after the tar would turn that kill into
            # a lost job.
            runtime_seconds = int(time.time() - start)
            _write_result(
                {
                    "status": "COMPLETED",
                    "tier": preset,
                    "designs_total": len(design_cifs),
                    "designs_completed": len(designs_out),
                    "designs": designs_out,
                    "artifact_keys": artifact_keys,
                    "target_chain": chain,
                    "target_length": n_res,
                    "target_asym_id": asym,
                    "contig": contig,
                    "binder_length": list(binder_length),
                    "hotspot_selections": selections,
                    "runtime_seconds": runtime_seconds,
                    "provider_job_id": os.environ.get("JOB_ID", ""),
                }
            )
        finally:
            # Ship the COMPLETE tree home before TemporaryDirectory deletes it.
            # In a finally so it also covers the _fail() exits above (each is a
            # sys.exit -> SystemExit through this block) and any unexpected
            # raise: a crashed or zero-design run is precisely when the tree
            # matters most.
            _ship_raw(workdir)

    send_heartbeat(
        webhook_url, job_id, stage="complete",
        designs_completed=len(designs_out), designs_total=len(designs_out),
    )
    logger.info("pipeline ok — %d designs, runtime=%ds", len(designs_out), runtime_seconds)


if __name__ == "__main__":
    main()
