def _ship_raw(work_dir: Path, dest: str | None = None) -> None:
    """Tar the COMPLETE work tree to ``dest`` before the work dir is destroyed.

    Same contract, and the same reasoning, as ``_ship_raw`` in
    tools/iggm/run_pipeline.py:123: a container must never decide which fields
    are worth keeping, and anything not shipped here is recoverable only by
    paying for the GPU again. For this tool the tree also holds the generated
    condition spec and both metrics CSVs -- the 89 columns of scope §5.8, of
    which the results page shows a handful.

    Unconditional, best-effort, never raises. ``dest`` resolves on call rather
    than at def time so a reassigned module constant is not ignored.
    """
    dst: str | None = None
    try:
        if dest is None:
            dest = RAW_ARCHIVE_PATH
        src = os.path.abspath(str(work_dir))
        if not os.path.isdir(src):
            logger.warning("[raw] no work dir to archive (nothing was created?): %s", src)
            return
        dst = os.path.abspath(dest)
        # The tar must never be written inside the tree it archives, or it tars
        # itself. /tmp/raw_archive.tgz is outside /tmp/rfd4_*/ by construction;
        # this guard is here so a future change to either path fails loudly in
        # the log instead of silently producing a self-referential archive.
        if dst == src or dst.startswith(src + os.sep):
            logger.warning(
                "[raw] refusing to archive: dest %s is inside the tree it archives (%s)",
                dst, src,
            )
            return
        # Stream to a file, never io.BytesIO — the latter costs ~3-4x peak RSS
        # on a multi-hundred-MB tree, this costs ~1x.
        with tarfile.open(dst, "w:gz") as tf:
            tf.add(src, arcname=os.path.basename(src.rstrip(os.sep)) or "work")
        logger.info("[raw] archived %s -> %s (%.1f MB)", src, dst, os.path.getsize(dst) / 1e6)
    except Exception as exc:
        logger.warning("[raw] capture failed (non-fatal): %s: %s", type(exc).__name__, exc)
        # A crash mid-write (e.g. ENOSPC) can leave a truncated but still-openable
        # .tgz at the destination; the wrapper parks whatever exists. Remove the
        # partial so a failed capture parks NOTHING rather than a tar that reports
        # success but cannot be read.
        try:
            if dst is not None and os.path.exists(dst):
                os.remove(dst)
        except OSError:
            pass


