def parse_payload() -> dict[str, Any]:
    raw = os.environ.get("JOB_PAYLOAD", "").strip()
    if not raw:
        _fail("preflight", "env", "JOB_PAYLOAD env var is empty")
    try:
        return json.loads(raw)
    except json.JSONDecodeError as exc:
        _fail("preflight", "env", f"JOB_PAYLOAD is not valid JSON: {exc}")
    return {}


def download_target(url: str, dest: Path) -> Path:
    if not url:
        _fail("input", "url", "input_presigned_url missing")
    try:
        with requests.get(url, stream=True, timeout=120) as resp:
            resp.raise_for_status()
            with open(dest, "wb") as fh:
                for chunk in resp.iter_content(chunk_size=32768):
                    if chunk:
                        fh.write(chunk)
    except Exception as exc:
        _fail("input", "download", f"target structure download failed: {exc}")
    if not dest.is_file() or dest.stat().st_size < 100:
        _fail("input", "download", "downloaded target structure is empty or tiny")
    return dest


# ===========================================================================
# mmCIF _atom_site reader
# ===========================================================================
#
# The only structure parser in this file. ``numbering.py`` writes CIF but reads
# none, and its ``ResidueEntry`` carries no atom names, while an atom-level
# hotspot needs the atom names a residue actually contains. One reader serves
# both input paths: a PDB upload is converted by ``numbering.pdb_to_cif`` and
# the PRODUCED CIF is then read here, so there is a single downstream code path.
#
# This is a trust boundary -- the bytes are a customer upload -- so the
# tokenizer handles the quoting mmCIF actually uses and refuses what it does not
# handle, rather than mis-parsing it.

_REQUIRED_ATOM_SITE_FIELDS = (
    "label_atom_id",
    "label_comp_id",
    "label_asym_id",
    "label_seq_id",
    "auth_asym_id",
    "auth_seq_id",
)


def _tokenize_cif_line(line: str) -> list[str]:
    """Split one mmCIF data line into tokens, honouring ' and " quoting.

    A quote opens a token only at a token boundary and closes it only when
    followed by whitespace or end of line, which is what lets an atom name like
    ``O5'`` stay one token (CIF 1.1 §2.2.7.3). ``numbering.py``'s writer relies
    on the same rule from the other side (``_closes_a_quoted_string``,
    tools/rfd4/numbering.py:681).
    """
    tokens: list[str] = []
    i = 0
    n = len(line)
    while i < n:
        if line[i].isspace():
            i += 1
            continue
        if line[i] == "#":
            break
        if line[i] in "'\"":
            quote = line[i]
            i += 1
            start = i
            while i < n:
                if line[i] == quote and (i + 1 >= n or line[i + 1].isspace()):
                    break
                i += 1
            tokens.append(line[start:i])
            i += 1
            continue
        start = i
        while i < n and not line[i].isspace():
            i += 1
        tokens.append(line[start:i])
    return tokens


def read_atom_site(cif_text: str) -> list[dict[str, str]]:
    """Return the ``_atom_site`` loop as one dict per atom row.

    Raises ``ValueError`` on anything this reader does not handle, rather than
    returning a partial parse: an atom list that silently lost rows produces a
    hotspot selection naming atoms the structure does not have.

    Rows may wrap across physical lines (CIF permits it), so tokens are
    accumulated until the loop ends and then chunked by the column count.
    A semicolon text field inside ``_atom_site`` is refused -- no ``_atom_site``
    value in the files this tool accepts needs one, and parsing it wrongly is
    worse than refusing it.
    """
    lines = cif_text.splitlines()
    i = 0
    while i < len(lines):
        if lines[i].strip().lower() != "loop_":
            i += 1
            continue
        tags: list[str] = []
        j = i + 1
        while j < len(lines):
            stripped = lines[j].strip()
            if stripped.startswith("_"):
                tags.append(stripped.split()[0])
                j += 1
                continue
            break
        if not any(t.startswith("_atom_site.") for t in tags):
            i = j
            continue
        if not all(t.startswith("_atom_site.") for t in tags):
            raise ValueError("a loop_ mixes _atom_site with another category")
        fields = [t.split(".", 1)[1] for t in tags]
        missing = [f for f in _REQUIRED_ATOM_SITE_FIELDS if f not in fields]
        if missing:
            raise ValueError(f"_atom_site is missing required columns: {missing}")
        tokens: list[str] = []
        while j < len(lines):
            stripped = lines[j].strip()
            if not stripped or stripped.startswith("#"):
                j += 1
                continue
            if stripped.startswith(";"):
                raise ValueError("semicolon text field inside _atom_site is not supported")
            low = stripped.lower()
            if stripped.startswith("_") or low == "loop_" or low.startswith("data_"):
                break
            tokens += _tokenize_cif_line(lines[j])
            j += 1
        if not tokens or len(tokens) % len(fields):
            raise ValueError(
                f"_atom_site has {len(tokens)} values for {len(fields)} columns"
            )
        rows = [
            dict(zip(fields, tokens[k : k + len(fields)]))
            for k in range(0, len(tokens), len(fields))
        ]
        # A multi-model structure is refused, not reduced to its first model.
        # Dropping models 2+ here would make OUR mapping, contig and hotspots
        # describe model 1 while ``load_target`` still hands upstream the file
        # as uploaded (:595), so the run would be conditioned on one
        # structure and generated against another.
        if rows and "pdbx_PDB_model_num" in fields:
            models = {r["pdbx_PDB_model_num"] for r in rows}
            if len(models) > 1:
                raise ValueError(
                    f"the structure has {len(models)} models; upload a single model"
                )
        return rows
    raise ValueError("no _atom_site loop found in the structure")


def _cif_opt(value: str) -> str:
    """mmCIF's two null tokens (``.`` absent, ``?`` unknown) as an empty string."""
    return "" if value in (".", "?") else value


def _residue_key(row: dict[str, str]) -> tuple[str, str, str, str, str]:
    return (
        row["label_asym_id"],
        row["label_seq_id"],
        row["auth_asym_id"],
        row["auth_seq_id"],
        _cif_opt(row.get("pdbx_PDB_ins_code", "")),
    )


def mapping_from_atom_site(rows: Iterable[dict[str, str]]) -> numbering.ResidueMapping:
    """Build a ``ResidueMapping`` from a CIF's own ``label_*``/``auth_*`` columns.

    Used on the CIF input path, where upstream's numbering is already in the
    file and inventing our own would contradict it. On the PDB path the mapping
    comes from ``numbering.pdb_to_cif`` instead and this is not called.

    ``ResidueMapping.__init__`` is what refuses a duplicate author residue or a
    duplicate ``label_seq_id`` (tools/rfd4/numbering.py:254-280); this function
    adds no refusal of its own beyond unparseable ids.
    """
    entries: list[numbering.ResidueEntry] = []
    asym_order: list[str] = []
    seen: set[tuple[str, str, str, str, str]] = set()
    for row in rows:
        key = _residue_key(row)
        if key in seen:
            continue
        seen.add(key)
        asym = row["label_asym_id"]
        if asym not in asym_order:
            asym_order.append(asym)
        raw_label = _cif_opt(row["label_seq_id"])
        raw_auth = _cif_opt(row["auth_seq_id"])
        if not raw_auth:
            raise ValueError(f"residue in asym {asym} has no auth_seq_id")
        try:
            auth_seq = int(raw_auth)
            label_seq = int(raw_label) if raw_label else None
        except ValueError as exc:
            raise ValueError(f"non-integer residue id in asym {asym}: {exc}") from exc
        raw_entity = _cif_opt(row.get("label_entity_id", ""))
        try:
            entity = int(raw_entity)
        except ValueError:
            # A non-numeric entity id is legal mmCIF. ResidueEntry types the
            # field as int, and nothing this file emits reads it, so asym order
            # stands in rather than failing the run over an unused field.
            entity = asym_order.index(asym) + 1
        entries.append(
            numbering.ResidueEntry(
                author=numbering.AuthorResidue(
                    chain=row["auth_asym_id"],
                    seq=auth_seq,
                    icode=_cif_opt(row.get("pdbx_PDB_ins_code", "")),
                ),
                resname=row["label_comp_id"],
                label_asym_id=asym,
                label_entity_id=entity,
                label_seq_id=label_seq,
            )
        )
    return numbering.ResidueMapping(entries)


def atom_names_by_residue(
    rows: Iterable[dict[str, str]],
) -> dict[tuple[str, int], tuple[str, ...]]:
    """``(label_asym_id, label_seq_id)`` -> the atom names present, in file order.

    Alternate conformations collapse: the names are de-duplicated, because a
    hotspot selection names atoms, not altlocs. Non-polymer rows
    (``label_seq_id`` null) are dropped -- ``hotspot_atoms_for_residue``'s
    precondition is a polymer residue (tools/rfd4/numbering.py:1109-1125).
    """
    out: dict[tuple[str, int], list[str]] = {}
    for row in rows:
        raw_label = _cif_opt(row["label_seq_id"])
        if not raw_label:
            continue
        try:
            key = (row["label_asym_id"], int(raw_label))
        except ValueError:
            continue
        names = out.setdefault(key, [])
        name = _cif_opt(row["label_atom_id"])
        if name and name not in names:
            names.append(name)
    return {k: tuple(v) for k, v in out.items()}


def crop_pdb_to_chain(pdb_text: str, chain: str) -> str | None:
    """Drop every coordinate record outside author chain ``chain``.

    Returns the cropped PDB text, or ``None`` for "do not crop", on which the
    caller keeps the whole upload. ``None`` comes back in two cases. First,
    ``chain`` carries no polymer atom by the test below: an unknown chain name,
    or one naming a water-only or plain-ligand chain, then
    reaches ``resolve_target_chain`` and gets that function's specific refusal
    instead of a cropped file with no polymer residue in it. Second, NO OTHER
    chain carries one either -- there is nothing to crop, and a single-chain
    upload must reach ``pdb_to_cif`` exactly as it does today, waters and
    ligands on their own chain ids included.

    The polymer test here is the condition ``_is_polymer`` puts on a residue's
    atoms: an atom named ``CA``, on an ``ATOM`` record or on a ``HETATM``
    record whose resname is in ``_MODRES_EQUIV``
    (tools/rfd4/numbering.py:138-148, :174-177). It reads the three column
    slices the parser reads, ``line[:6]``, ``line[12:16]`` and ``line[17:20]``
    (tools/rfd4/numbering.py:568, :637, :643). The ``_MODRES_EQUIV`` half is
    not decoration: without it a protein chain plus a free modified amino acid
    on its own chain id -- MSE, SEP, PCA and the rest carry a ``CA`` -- was
    left uncropped while ``_polymer_chains`` still listed that id, so the run
    was funded and then refused in this container, which is the defect this
    function exists to close
    (``test_a_modified_residue_ligand_on_its_own_chain_is_cropped_away``).

    A coordinate record too short to hold coordinates is KEPT whatever chain
    it claims: ``pdb_to_cif`` raises on such a line
    (tools/rfd4/numbering.py:571-575) and ``load_target`` turns that into a
    refusal, so a truncated upload is still refused rather than converted with
    a residue quietly missing
    (``test_a_truncated_coordinate_record_survives_the_crop``).

    WHAT SURVIVES THE CROP: the named chain's coordinate records, ``ATOM`` and
    ``HETATM`` alike, each line's 80 columns unaltered -- not byte for byte,
    because ``splitlines()`` plus ``"\n".join`` rewrites a CRLF upload as LF.
    That cannot reach a design: ``_parse_atoms`` splits on lines and slices
    fixed columns (tools/rfd4/numbering.py:566-575), so it never sees a
    terminator, and the cropped text is a temporary handed straight to
    ``pdb_to_cif``. WHAT IS DROPPED: every
    coordinate record carrying a different chain id -- the other polymer chains
    and, with them, their ligands, glycans and waters, because in PDB format
    those normally carry the chain id of the chain they sit on, which is the
    reason ``pdb_to_cif`` splits them into their own asym
    (tools/rfd4/numbering.py:944-950). Non-coordinate records are left alone;
    ``pdb_to_cif`` reads only ``ATOM``/``HETATM`` and stops at ``ENDMDL``
    (tools/rfd4/numbering.py:566-570), so no other record reaches upstream's
    numbering either way.

    Net of those two, nothing outside the target chain reaches upstream, which
    is the direction the sibling normalizers take with ``keep_hetatm=False,
    keep_waters=False`` (``shared/pipeline_normalize.py::normalize_for_rfd4``,
    and the identical preset in ``normalize_for_rfdiffusion`` /
    ``normalize_for_bindcraft`` / ``normalize_for_rfantibody``). It is NOT
    identical to them in one respect, deliberately: a water or ligand sharing
    the TARGET chain's id survives here, as it already does for a single-chain
    upload today (``test_a_single_polymer_chain_is_picked_even_with_non_polymer
    _chains``). Keeping one shape for cropped and uncropped uploads is the
    reason. A single-chain upload is left alone entirely, by the
    ``other_polymer_chain`` test below -- waters and ligands on their own chain
    ids reach upstream exactly as they do today
    (``test_a_single_chain_upload_is_not_cropped_at_all``). ``shared/`` is not importable in the rfd4
    container (``tools/rfd4/modal_app.py``), so the sibling behaviour is matched
    by contract, not by calling it.

    RESIDUE NUMBERING IS NOT TOUCHED, matching the ``renumber_residues=False``
    of the rfdiffusion / proteina / rfantibody / bindcraft / rfd4 presets
    (``normalize_for_pxdesign`` and ``normalize_for_boltzgen`` do renumber, so
    this is those five, not a house-wide rule) and the reason given there --
    numbering is
    load-bearing, because a hotspot resolves through ``label_seq_id``.
    ``pdb_to_cif`` counts ``label_seq_id`` per asym from 1 over that asym's own
    polymer residues (tools/rfd4/numbering.py:957-966), and the crop changes
    neither the named chain's polymer residues nor their file order, so every
    ``label_seq_id`` in the kept chain is the same before and after
    (``test_cropping_a_dimer_leaves_the_kept_chains_label_numbering_identical``).
    """
    kept: list[str] = []
    has_polymer_atom = False
    other_polymer_chain = False
    in_first_model = True
    for line in pdb_text.splitlines():
        record = line[:6]
        if record in ("ATOM  ", "HETATM"):
            if len(line) < 54:
                # Too short for `pdb_to_cif`, which raises on it; keep it so
                # that refusal still fires instead of dropping the residue.
                kept.append(line)
                continue
            is_polymer_atom = (
                in_first_model
                and line[12:16].strip() == "CA"
                and (
                    record == "ATOM  "
                    or line[17:20].strip().upper() in numbering._MODRES_EQUIV
                )
            )
            if line[21:22].strip() != chain:
                if is_polymer_atom:
                    other_polymer_chain = True
                continue
            if is_polymer_atom:
                has_polymer_atom = True
        elif line.startswith("ENDMDL"):
            in_first_model = False
        kept.append(line)
    if not has_polymer_atom or not other_polymer_chain:
        return None
    return "\n".join(kept) + "\n"


def load_target(
    path: Path, work_dir: Path, requested_chain: str = ""
) -> tuple[Path, numbering.ResidueMapping, dict[tuple[str, int], tuple[str, ...]]]:
    """Resolve an uploaded PDB or CIF to (cif path for upstream, mapping, atoms).

    The sniff is the presence of an ``_atom_site.`` tag or a ``data_`` block
    header, which is what distinguishes an mmCIF from a PDB regardless of the
    filename the customer uploaded under.

    WHERE THE CROP HAPPENS, and why here rather than in
    ``resolve_target_chain``. Leo's decision of 2026-11-10 (scope doc section 9
    item 11) is that the CONTAINER crops a multi-chain upload to the named
    target chain, with no hub-side refusal and no preflight change. The crop
    runs on the PDB TEXT, before ``pdb_to_cif``, so upstream receives the one
    file shape single-chain runs have always sent: one polymer entity, one
    asym, every ``_entity``/``_entity_poly_seq``/``_struct_asym`` row consistent
    with the atoms, all emitted by the same writer. Cropping after conversion
    would mean re-emitting those four categories by hand from parsed rows,
    which is a second CIF writer and a second chance to disagree with the
    first. ``resolve_target_chain`` is handed a mapping, not the file, and
    keeps the refusals for what genuinely cannot proceed.

    A CIF upload is NOT cropped: there is no CIF writer in this container, and
    the four hub paths that stage a target convert a ``.cif``/``.mmcif``
    upload to PDB bytes before staging (``blueprints/tools.py:1773``, ``:2193``,
    ``blueprints/prep.py:132``, ``shared/pdb_intake.py:563``), so the customer
    path is the PDB path. Those four are cited, not enumerated: I did not prove
    no fifth entry point exists. A multi-chain CIF reaching this function is still
    refused by ``resolve_target_chain``.
    """
    try:
        text = path.read_text(errors="replace")
    except OSError as exc:
        _fail("input", "read", f"could not read the uploaded structure: {exc}")
        raise
    is_cif = "_atom_site." in text or any(
        ln.strip().lower().startswith("data_") for ln in text.splitlines()[:50]
    )
    if is_cif:
        cif_path = path
        cif_text = text
    else:
        picked = (requested_chain or "").strip()
        if picked:
            cropped = crop_pdb_to_chain(text, picked)
            if cropped is not None:
                text = cropped
        try:
            cif_text, mapping = numbering.pdb_to_cif(text)
        except numbering.NumberingError as exc:
            _fail("input", "numbering", f"PDB could not be converted: {exc}")
            raise
        cif_path = work_dir / "target.cif"
        cif_path.write_text(cif_text)
    try:
        rows = read_atom_site(cif_text)
    except ValueError as exc:
        _fail("input", "cif", f"could not read the structure's atom records: {exc}")
        raise
    if is_cif:
        try:
            mapping = mapping_from_atom_site(rows)
        except (ValueError, numbering.NumberingError) as exc:
            _fail("input", "cif", f"the structure's residue numbering is unusable: {exc}")
            raise
    return cif_path, mapping, atom_names_by_residue(rows)


