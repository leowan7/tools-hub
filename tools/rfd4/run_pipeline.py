"""Modal entrypoint for RFD4-Proteina de-novo binder generation.

Reads job configuration from ``JOB_PAYLOAD`` (the same env-var contract as the
other atomic tools: iggm / boltz2 / af2), builds upstream's condition spec from
the customer's target structure, runs ``rfd4-generate`` once, uploads each
generated complex CIF via a presigned PUT as it appears, emits a
``new_candidate`` heartbeat per design, and writes the final summary to
``/tmp/smoke_results.json``. The Modal wrapper returns that file inline (see
``tools/rfd4/modal_app.py``).

NOT the same model line as ``tools/proteina/`` (NVIDIA Proteina-Complexa).

Reachability: ``rfd4`` is absent from the deploy matrix in
``.github/workflows/deploy-modal.yml`` and from the tool catalog, so nothing in
this file is reachable by a customer. Scope doc §8 adds the adapter with the
feature flag OFF at step 3 (line 1088), the deploy at step 6, and the flag flip
at step 8.

NUMBERING. Upstream resolves every residue id in a condition spec against the
mmCIF ``label_seq_id``, not author numbering (scope §4.1). Customers submit
author numbering. That translation lives in ``tools/rfd4/numbering.py`` (PR
#477) and is imported here -- it is not reimplemented. The one thing this file
adds on top is an ``_atom_site`` reader, because ``numbering.py`` ships no CIF
reader and ``ResidueEntry`` carries no atom names, and atom-level hotspots need
both.

SAVE AS YOU GO: each design is uploaded and streamed while ``rfd4-generate`` is
still running. Scope §5.8's rung-4 artefact
(``docs/scoping/rung4-probe/gpu_result_20261103T114437.json``) timed all eight
designs of a real run appearing one at a time between 128.2 s and 196.3 s, with
both metrics CSVs landing in the same poll interval as the LAST design -- so no
score exists at stream time and a ``new_candidate`` here carries ids only. See
``sweep_designs``.

WHAT HAS AND HAS NOT RUN. Every constant below that came from a measurement
names its scope-doc section. Two things this file emits have never been seen by
a GPU, both recorded in the report for this PR and in the comments at their
definition: the atom-level hotspot expression, and a condition spec generated by
this repo at all (the paid rung-4 run was redirected onto upstream's own
example spec ``condition_spec_ppi.yaml``, scope §5.8 line 517).
"""

