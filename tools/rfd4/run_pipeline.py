# ``-`` is NOT a separator here: in ``[\s_:-]*`` it swallowed the sign of a
# negative author residue number, so ``A-5`` read as residue 5. The hub's own
# parser reads it as -5 (shared/pdb_inspect.py:367, :375) and the two
# vocabularies have to agree.
_HOTSPOT_TOKEN = re.compile(r"^([A-Za-z])?[\s_:]*(-?\d+)$")


def _polymer_chains(mapping: numbering.ResidueMapping) -> list[str]:
    # ``chains()`` returns a frozenset (tools/rfd4/numbering.py:327), so sort:
    # these names reach the customer in a refusal message, and an unordered
    # set would also make which chain a single-chain run picks depend on hash
    # order.
    return sorted(c for c in mapping.chains() if mapping.polymer_entries(c))


def resolve_target_chain(mapping: numbering.ResidueMapping, requested: str) -> str:
    """The one author chain this run designs against.

    A RUN STILL DESIGNS AGAINST ONE CHAIN. Scope §4.2 proposes "multi-chain
    allowed"; what the six free-CPU variants measured is narrower, and that row
    carries the detail. Of the five naming two target chains, V1 and V5 carry
    committed ``index_group_molecule_must_be_connected`` tracebacks; V2 returned
    rc 1 with no CIF but had its result JSON overwritten by the V5/V7 sweep, so
    reading V2 as the same invariant failure is inference from an exit code, not
    a trace. V3 and V7 returned 0 and BUILT a CIF -- and those two are exactly
    the ones whose second chain is UNINDEXED (V3 both chains, V7 chain B only),
    which makes the measured rule **at most one indexed target chain** rather
    than one chain outright. An unindexed chain is not a conditioned target, so
    neither run is a two-chain target accepted upstream. Lifting this rule needs
    a run upstream accepts with two INDEXED chains; none exists, and the
    mechanism is UNVERIFIED.

    WHAT CHANGED 2026-11-10 (Leo's decision, scope doc section 9 item 11): a
    multi-chain upload with a target chain NAMED is no longer refused. The
    customer case this blocked is the ordinary one -- upload a crystal dimer,
    name the antigen chain -- and nothing hub-side mirrored the refusal, so the
    run took a wallet hold, started the GPU and died in the container with the
    customer paying the start minimum for zero designs. ``load_target`` now
    crops the upload to the named chain before converting it, so by the time
    this function runs on a PDB upload there is one polymer chain left; see
    ``load_target``'s docstring for what the crop keeps and why it is not in
    this function. The refusals below remain for what genuinely cannot proceed:
    no polymer chain at all, a named chain the upload does not hold, a
    multi-chain upload with NO chain named (there is nothing to pick on the
    customer's behalf -- a guess costs them a run that designs against one
    protomer while looking entirely successful, the shape recorded for proteina
    in ``proteina-hotspot-chain-semantics``), and a chain split across asym
    units. The named-chain-plus-others branch stays reachable on an mmCIF upload,
    which this container cannot crop because it has no CIF writer; a PDB
    reaches it only if ``crop_pdb_to_chain`` declined the file, so its message
    names no file format.
    """
    chains = _polymer_chains(mapping)
    if not chains:
        _fail("input", "chain", "the uploaded structure contains no polymer chain")
    picked = (requested or "").strip()
    if picked:
        if picked not in chains:
            _fail(
                "input", "chain",
                f"chain {picked!r} is not a polymer chain of the upload "
                f"(found: {', '.join(chains)})",
            )
        others = [c for c in chains if c != picked]
        if others:
            # The customer input that reaches here is an mmCIF upload: no CIF
            # writer in this container to re-emit consistent entity rows. A
            # PDB reaches it only if `crop_pdb_to_chain` declined the file --
            # see its `None` cases -- so the message names no file format,
            # which would be wrong for one of the two.
            _fail(
                "input", "chain",
                f"the upload holds more than one polymer chain ({', '.join(chains)}) "
                f"and could not be cropped to chain {picked}. Crop the structure "
                f"to chain {picked} and resubmit it as PDB.",
            )
    elif len(chains) > 1:
        _fail(
            "input", "chain",
            f"the upload holds {len(chains)} polymer chains ({', '.join(chains)}) "
            "and no target chain was named; name the chain to design against "
            "and resubmit as PDB, and the file will be cropped to that chain. "
            "An mmCIF is not cropped, so crop it yourself or convert it first.",
        )
    else:
        picked = chains[0]
    asyms = {e.label_asym_id for e in mapping.polymer_entries(picked)}
    if len(asyms) != 1:
        # Every id in the spec is a label id, and one spec segment names one
        # asym, so a chain split across asyms has no single contig segment.
        _fail(
            "input", "chain",
            f"author chain {picked!r} spans {len(asyms)} mmCIF asym units "
            f"({', '.join(sorted(asyms))}); this tool cannot build one contig "
            "segment for it.",
        )
    return picked


def validate_sizes(
    mapping: numbering.ResidueMapping, chain: str, binder_length: tuple[int, int]
) -> int:
    """Refuse a target outside §4.3's bounds. Returns the target residue count.

    Enforced here as well as at the form because this is the trust boundary the
    GPU sits behind: scope §4.3 gives ``min_target_aa`` 30,
    ``hard_cap_target_aa`` 400 and ``hard_cap_combined_aa`` 520, the last of
    which is also what ``tools/rfd4/modal_app.py``'s session timeout is sized
    against.
    """
    n_res = len(mapping.polymer_entries(chain))
    # The two maxima are enforced on the chain's LABEL SPAN, not on its observed
    # residue count, because the span is what the contig hands upstream
    # (``build_contig``, :898). An uploaded mmCIF with unobserved residues
    # leaves gaps in ``_atom_site``, so the span can exceed the count without
    # limit; capping only the count would let a gapped file past the guard that
    # bounds what the GPU is given.
    lo, hi = numbering.label_range_for_chain(mapping, chain)
    span = hi - lo + 1
    if n_res < MIN_TARGET_AA:
        _fail(
            "input", "target_size",
            f"target chain {chain} has {n_res} residues; the minimum is {MIN_TARGET_AA}",
        )
    if span > HARD_CAP_TARGET_AA:
        _fail(
            "input", "target_size",
            f"target chain {chain} spans {span} residues; the maximum is "
            f"{HARD_CAP_TARGET_AA}",
        )
    combined = span + binder_length[1]
    if combined > HARD_CAP_COMBINED_AA:
        _fail(
            "input", "target_size",
            f"target ({span} aa) plus the longest binder ({binder_length[1]} aa) "
            f"is {combined} aa; the maximum is {HARD_CAP_COMBINED_AA}",
        )
    return n_res


def parse_num_designs(raw: Any) -> int:
    """How many designs this run generates.

    ``int(raw or DEFAULT)`` is the house idiom (tools/proteina/run_pipeline.py:2788)
    and it sends 0 and ``"0"`` to the default, so a request for zero designs
    would run -- and bill -- the default eight. Only an absent value defaults.
    """
    if raw is None or raw == "":
        raw = DEFAULT_NUM_DESIGNS
    try:
        num_designs = int(raw)
    except (TypeError, ValueError):
        _fail("input", "nsamples", f"nsamples is not an integer: {raw!r}")
        raise
    if num_designs < 1:
        _fail("input", "nsamples", f"nsamples must be at least 1, got {num_designs}")
    return num_designs


def parse_binder_length(raw: Any) -> tuple[int, int]:
    if not raw:
        return DEFAULT_BINDER_LENGTH
    try:
        values = [int(v) for v in raw]
    except (TypeError, ValueError):
        _fail("input", "binder_length", f"binder_length is not a pair of integers: {raw!r}")
        raise
    if len(values) != 2:
        _fail("input", "binder_length", f"binder_length needs exactly two values: {raw!r}")
    lo, hi = values
    if lo > hi:
        lo, hi = hi, lo
    if lo < BINDER_LENGTH_FLOOR or hi > BINDER_LENGTH_CEILING:
        _fail(
            "input", "binder_length",
            f"binder length {lo}-{hi} is outside the supported range "
            f"{BINDER_LENGTH_FLOOR}-{BINDER_LENGTH_CEILING}",
        )
    return lo, hi


def hotspot_tokens(job_spec: dict[str, Any]) -> list[str]:
    """The hotspot tokens the customer picked, from either field name.

    Same two field names as proteina (``hotspot_spec`` wins over
    ``hotspot_residues``, tools/proteina/run_pipeline.py:952-957) so the
    adapter step 3 writes has one vocabulary to target.
    """
    for field in ("hotspot_spec", "hotspot_residues"):
        raw = job_spec.get(field)
        if raw is None:
            continue
        if isinstance(raw, str):
            items = [t for t in re.split(r"[,\s]+", raw.strip()) if t]
        elif isinstance(raw, (list, tuple)):
            items = [str(t).strip() for t in raw if str(t).strip()]
        else:
            _fail("input", "hotspots", f"{field} is neither a string nor a list")
            raise AssertionError  # unreachable: _fail exits
        if items:
            return items
    return []


def build_hotspot_selections(
    mapping: numbering.ResidueMapping,
    atoms: dict[tuple[str, int], tuple[str, ...]],
    tokens: list[str],
    default_chain: str,
) -> list[str]:
    """One atom-level selection expression per picked residue.

    ATOM SET. Which atoms a hotspot names is scope §10 item 6, and it is still
    Leo's to decide. The choice lives in ONE place --
    ``numbering.RFD4_HOTSPOT_ATOM_SET`` (tools/rfd4/numbering.py:1085) and the
    ``hotspot_atoms_for_residue`` that reads it -- and this function only calls
    it. §10A's recommendation (option B, side-chain heavy atoms) is what that
    constant holds; §10A also names option D as the upgrade if a run shows B
    over-constrains.

    NOT YET ACCEPTED BY UPSTREAM. The only hotspot form any committed artefact
    has had accepted is the three-field residue-list form
    ``sel('A/*/[17, 19]')`` (``docs/scoping/rung4-probe/spec_v4_chainA.yaml``,
    prevalidated at exit 0 in ``cpu_result_20261103T103209.json``). That form
    names no atoms, so it is not one of §10A's options at all; it is the shape
    §10A exists to replace. The
    four-field atom-level form emitted here is §4.1's documented shape and the
    form ``format_hotspot_selection`` renders; the same probe's
    ``condition_CoordinateGroup_1_atom`` readback proves the four-field form
    parses and applies per atom within a residue, but with ``*`` in the residue
    field, not a concrete id. A run will be the first test of this exact
    expression with a concrete residue id in it.
    """
    if not tokens:
        _fail(
            "preflight", "missing_hotspots",
            "no hotspot residues were given; this tool runs upstream's "
            "hotspot-conditioned configuration and has nothing to condition on",
        )
    if len(tokens) > MAX_HOTSPOTS:
        _fail(
            "input", "hotspots",
            f"{len(tokens)} hotspot residues were given; the maximum is {MAX_HOTSPOTS}",
        )
    selections: list[str] = []
    seen: set[tuple[str, int]] = set()
    # ``author_for`` returns an AuthorResidue, which carries no residue name
    # (tools/rfd4/numbering.py:189-211); the name lives on ResidueEntry
    # (:219-230), so index the polymer entries by where they landed in the CIF.
    by_label = {
        (e.label_asym_id, e.label_seq_id): e for e in mapping.polymer_entries()
    }
    for token in tokens:
        match = _HOTSPOT_TOKEN.match(token)
        if not match:
            # Insertion codes land here. ``shared/pdb_inspect.split_hotspot``
            # parses a hotspot's residue number with ``int()``
            # (shared/pdb_inspect.py:367, :375), so a token like ``B52A`` never
            # survives the picker that produces these either; refusing is what
            # the author-numbering contract in
            # tools/rfd4/numbering.py:189-211 already assumes.
            _fail(
                "input", "hotspots",
                f"hotspot {token!r} is not a chain letter plus a residue number "
                "(insertion codes are not supported)",
            )
        chain = (match.group(1) or default_chain).strip()
        seq = int(match.group(2))
        try:
            asym, label_seq = mapping.label_for(chain, seq)
        except numbering.NumberingError as exc:
            _fail("input", "hotspots", f"hotspot {token!r}: {exc}")
            raise
        if (asym, label_seq) in seen:
            continue
        seen.add((asym, label_seq))
        # ``label_for`` refuses a non-polymer residue
        # (tools/rfd4/numbering.py:287-315), so the key is present.
        entry = by_label[(asym, label_seq)]
        observed = atoms.get((asym, label_seq), ())
        if not observed:
            _fail(
                "input", "hotspots",
                f"hotspot {token!r} has no atom records in the structure",
            )
        try:
            names = numbering.hotspot_atoms_for_residue(entry.resname, observed)
            selections.append(numbering.format_hotspot_selection(asym, label_seq, names))
        except numbering.NumberingError as exc:
            _fail("input", "hotspots", f"hotspot {token!r}: {exc}")
            raise
    return selections


def _yaml_dq(value: str) -> str:
    """One double-quoted YAML scalar, or a refusal.

    The spec is written by hand rather than through a YAML library, because
    nothing in the image is guaranteed to hold one and the document is four
    keys deep. That makes quoting this file's job: a value carrying ``"`` or
    ``\\`` would change the document's shape, and every value here is either a
    path we built or an id read from a customer upload, so it is refused rather
    than escaped.
    """
    if any(c in value for c in '"\\') or any(ord(c) < 32 for c in value):
        raise ValueError(f"value cannot be written to the condition spec: {value!r}")
    return f'"{value}"'


def build_contig(
    mapping: numbering.ResidueMapping, chain: str, binder_length: tuple[int, int]
) -> str:
    """Upstream's contig for one binder against one target chain.

    Shape taken from the only spec our stack has had accepted by upstream's own
    prevalidator, ``docs/scoping/rung4-probe/spec_v4_chainA.yaml``:
    ``"60-120, /0, A10-220"`` -- the binder length range, a chain break, then
    the target segment in LABEL numbering (scope §4.1).

    The segment covers the chain's whole label range.
    ``label_range_for_chain``'s docstring leaves to step 2 whether RFD4 requires
    that; this emits a full-coverage segment because that is the only form
    measured, not because a partial one is known to be refused.
    """
    lo, hi = numbering.label_range_for_chain(mapping, chain)
    asym = mapping.polymer_entries(chain)[0].label_asym_id
    return f"{binder_length[0]}-{binder_length[1]}, /0, {asym}{lo}-{hi}"


def write_condition_spec(
    spec_path: Path,
    *,
    cif_path: Path,
    contig: str,
    asym: str,
    hotspot_selections: list[str],
) -> Path:
    """Write upstream's condition spec for this run.

    Every line's shape is ``spec_v4_chainA.yaml``'s, the one spec of ours that
    upstream's CPU prevalidator (``/opt/rfd4/scripts/write_condition_spec_cifs.py``)
    has accepted -- scope §5.8, ``docs/scoping/rung4-probe/cpu_result_20261103T103209.json``
    (exit 0). That spec carried a single hotspot entry; whether several entries
    under one condition key are unioned is UNVERIFIED, and a run will be the
    first test of it.
    """
    crdgrp = f"sel('{asym}/*/*/[N,CA,C,O]') and not has_nan_coord()"
    seq = f"sel('{asym}')"
    lines = [
        f"{SPEC_KEY}:",
        f"  input: {_yaml_dq(str(cif_path))}",
        f"  contig: {_yaml_dq(contig)}",
        "  conditions:",
        "    C_CRDGRP:",
        "      1:",
        f"        - select: {_yaml_dq(crdgrp)}",
        "    C_SEQ:",
        "      true:",
        f"        - select: {_yaml_dq(seq)}",
    ]
    if hotspot_selections:
        lines += ["    C_HOT:", "      true:"]
        lines += [f"        - select: {_yaml_dq(sel)}" for sel in hotspot_selections]
    spec_path.write_text("\n".join(lines) + "\n")
    return spec_path


